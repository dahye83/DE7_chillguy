CREATE OR REPLACE TABLE TEAM_7_CHILL.GOLD.GD_AIRLINE_DELAY_REASON AS
SELECT DELAY_REASON, 
       AIRLINE, 
       COUNT(*) as CNT,
       ROW_NUMBER() OVER (
            PARTITION BY DELAY_REASON 
            ORDER BY COUNT(*) DESC
        ) AS rank
FROM SILVER.SL_AIRPORT_SCHEDULE_STATIC_YEARLY
WHERE DELAY_REASON IS NOT NULL
GROUP BY DELAY_REASON, AIRLINE
ORDER BY 1, 3 DESC;
