CREATE OR REPLACE TABLE TEAM_7_CHILL.GOLD.GD_AIRLINE_DELAY_INFO AS
SELECT AIRLINE
	 , ROUND(SUM(CASE WHEN STATUS = '지연' THEN 1 ELSE 0 END) / COUNT(*),2) AS DELAY_RT
	 , ROUND(AVG(DELAY_TM),1) AS AVG_DELAY_TM
	 , SUM(CASE WHEN STATUS = '지연' THEN 1 ELSE 0 END) as DELAY_FLIGHT_CNT
	 , COUNT(*) as FLIGHT_CNT
FROM TEAM_7_CHILL.SILVER.SL_AIRPORT_SCHEDULE_STATIC_YEARLY
GROUP BY AIRLINE
ORDER BY 2 DESC;