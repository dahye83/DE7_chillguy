CREATE OR REPLACE TABLE TEAM_7_CHILL.GOLD.GD_DELAY_WEEKDAY AS
SELECT WEEKDAY
	 , ROUND(SUM(CASE WHEN STATUS = '지연' THEN 1 ELSE 0 END) / COUNT(*),2) AS DELAY_RT
	 , ROUND(AVG(DELAY_TM),1) as AVG_DELAY_TM
	 , COUNT(*) as FLIGHT_CNT
FROM SILVER.SL_AIRPORT_SCHEDULE_STATIC_YEARLY
GROUP BY 1
ORDER BY 
    CASE WEEKDAY
        WHEN '월요일' THEN 1
        WHEN '화요일' THEN 2
        WHEN '수요일' THEN 3
        WHEN '목요일' THEN 4
        WHEN '금요일' THEN 5
        WHEN '토요일' THEN 6
        WHEN '일요일' THEN 7
    END;
